class AttentionRMSNorm(nn.Module):
    """Sana-style learnable RMS norm on caption hidden states."""

    def __init__(self, dim: int, scale_factor: float = 0.01, eps: float = 1e-6) -> None:
        super().__init__()
        self.eps = eps
        self.weight = nn.Parameter(torch.ones(dim) * scale_factor)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        # Upcast BEFORE squaring (Llama convention): squaring in bf16 and reducing over
        # ~1e3 elements loses mantissa bits exactly where the rsqrt is most sensitive.
        x_fp32 = x.float()
        normed = x_fp32 * torch.rsqrt(x_fp32.square().mean(dim=-1, keepdim=True) + self.eps)
        weight = self.weight.view(*([1] * (x.ndim - 2)), -1)
        return (weight.float() * normed).to(dtype=x.dtype)


class CaptionEmbedder(nn.Module):
    """Sana-style caption projection plus CFG null caption storage."""

    def __init__(self, in_channels: int, hidden_size: int, token_num: int) -> None:
        super().__init__()
        self.y_proj = nn.Sequential(
            nn.Linear(in_channels, hidden_size),
            nn.GELU(approximate="tanh"),
            nn.Linear(hidden_size, hidden_size),
        )
        null_init = torch.randn(token_num, in_channels) / math.sqrt(in_channels)
        self.null_text_embedding = nn.Parameter(null_init.unsqueeze(0))

    def forward(self, caption: torch.Tensor) -> torch.Tensor:
        return self.y_proj(caption)

    def null_condition(
        self,
        batch_size: int,
        *,
        device: torch.device | str,
        dtype: torch.dtype,
        mask_dtype: torch.dtype | None = None,
        token_num: int | None = None,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        text = self.null_text_embedding
        # Under FSDP2 the root shard turns this parameter into a DTensor, and this
        # method runs OUTSIDE the root forward (condition dropout happens before the
        # model call), so no unshard hook fires. Materialize the full tensor —
        # full_tensor() is differentiable, so the learned null caption still trains.
        if hasattr(text, "full_tensor"):
            text = text.full_tensor()
        if token_num is not None and token_num != text.shape[1]:
            if token_num < text.shape[1]:
                text = text[:, :token_num]
            else:
                pad = text.new_zeros(text.shape[0], token_num - text.shape[1], text.shape[2])
                text = torch.cat([text, pad], dim=1)
        text = text.expand(batch_size, -1, -1).to(device=device, dtype=dtype)
        mask = torch.ones(
            batch_size,
            text.shape[1],
            device=device,
            dtype=mask_dtype or torch.long,
        )
        if token_num is not None and token_num > self.null_text_embedding.shape[1]:
            mask[:, self.null_text_embedding.shape[1] :] = 0
        return text, mask


class FourierTimestepEmbedder(nn.Module):
    """DiT-style sinusoidal timestep features followed by an MLP.

    Flow sigmas live in [0, 1]; they are scaled by 1000 before the frequency bank
    (matching the DiT/SD3 convention) so the sinusoids resolve fine timestep
    distinctions near the endpoints, where a raw-scalar Linear gives the network
    only one feature to carve the whole range from.
    """

    def __init__(self, hidden_dim: int, freq_dim: int = 256, max_period: float = 10000.0) -> None:
        super().__init__()
        if freq_dim % 2 != 0:
            raise ValueError(f"freq_dim must be even, got {freq_dim}")
        half = freq_dim // 2
        freqs = torch.exp(-math.log(max_period) * torch.arange(half).float() / half)
        self.register_buffer("freqs", freqs, persistent=False)
        self.net = nn.Sequential(
            nn.Linear(freq_dim, hidden_dim),
            nn.SiLU(),
            nn.Linear(hidden_dim, hidden_dim),
        )

    def forward(self, timesteps: torch.Tensor) -> torch.Tensor:
        angles = timesteps.float().view(-1, 1) * 1000.0 * self.freqs[None]
        features = torch.cat([angles.cos(), angles.sin()], dim=-1)
        return self.net(features.to(dtype=self.net[0].weight.dtype))


class TimestepEmbedder(nn.Module):
    def __init__(self, hidden_dim: int) -> None:
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(1, hidden_dim),
            nn.SiLU(),
            nn.Linear(hidden_dim, hidden_dim),
        )

    def forward(self, timesteps: torch.Tensor) -> torch.Tensor:
        dtype = self.net[0].weight.dtype
        return self.net(timesteps.to(dtype=dtype).view(-1, 1))


