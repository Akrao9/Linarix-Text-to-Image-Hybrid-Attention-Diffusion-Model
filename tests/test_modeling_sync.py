"""modeling_boomer_fla.py must stay in lockstep with the training sources.

The modeling file is generated by tools/gen_modeling_file.py; hand-drift here
used to publish checkpoints that silently ran the wrong architecture (missing
shared-adaLN, fourier timesteps, then the whole v6 feature trio).
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from boomer.models.boomer_fla_dit import BoomerFLADiTConfig  # noqa: E402
from boomer.models.factory import create_model  # noqa: E402


def _load_modeling_module():
    spec = importlib.util.spec_from_file_location(
        "modeling_boomer_fla", ROOT / "modeling_boomer_fla.py"
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("modeling_boomer_fla", module)
    spec.loader.exec_module(module)
    return module


def test_modeling_file_is_generated_and_current() -> None:
    sys.path.insert(0, str(ROOT / "tools"))
    try:
        import gen_modeling_file
    finally:
        sys.path.pop(0)
    generated = gen_modeling_file.generate()
    current = (ROOT / "modeling_boomer_fla.py").read_text(encoding="utf-8")
    assert current == generated, (
        "modeling_boomer_fla.py is stale — rerun: python tools/gen_modeling_file.py"
    )


def test_config_fields_match_training_config() -> None:
    import dataclasses

    m = _load_modeling_module()
    train_fields = {f.name for f in dataclasses.fields(BoomerFLADiTConfig)}
    export_fields = {f.name for f in dataclasses.fields(m.BoomerFLADiTConfig)}
    assert train_fields == export_fields


def test_v6_state_dict_and_forward_parity() -> None:
    m = _load_modeling_module()
    kw = dict(
        hidden_dim=64,
        depth=4,
        num_heads=4,
        mlp_ratio=2.0,
        mixer_type="fallback",
        cross_attention_backend="sdpa",
        image_attention_every=2,
        dual_stream_depth=1,
        multimodal_coord_ids=True,
        joint_refresh_attention=True,
        sandwich_rmsnorm=True,
        rope_ntk_factor=2.0,
        shared_adaln=True,
        use_abs_pos_embed=False,
    )
    torch.manual_seed(0)
    train_model = create_model(BoomerFLADiTConfig(**kw)).eval()
    export_model = m.BoomerFLADiT(m.BoomerFLADiTConfig(**kw)).eval()
    export_model.load_state_dict(train_model.state_dict(), strict=True)

    latent = torch.randn(2, 32, 16, 16)
    timesteps = torch.rand(2)
    text = torch.randn(2, 300, 1536)
    mask = torch.ones(2, 300)
    mask[:, 250:] = 0
    with torch.no_grad():
        out_train = train_model(latent, timesteps, text, mask)
        out_export = export_model(latent, timesteps, text, mask)
    assert torch.equal(out_train, out_export)


def test_legacy_glumbconv_keys_load_into_modeling_model() -> None:
    m = _load_modeling_module()
    kw = dict(
        hidden_dim=64,
        depth=2,
        num_heads=4,
        mlp_ratio=2.0,
        mixer_type="fallback",
        cross_attention_backend="sdpa",
        use_abs_pos_embed=False,
    )
    model = m.BoomerFLADiT(m.BoomerFLADiTConfig(**kw))
    state = model.state_dict()
    legacy = {}
    for key, value in state.items():
        if key.endswith("mlp.inverted_fc.0.weight"):
            key, value = key.replace("inverted_fc.0.weight", "inverted_conv.conv.weight"), value.unsqueeze(-1).unsqueeze(-1)
        elif key.endswith("mlp.inverted_fc.0.bias"):
            key = key.replace("inverted_fc.0.bias", "inverted_conv.conv.bias")
        elif key.endswith("mlp.point_fc.weight"):
            key, value = key.replace("point_fc.weight", "point_conv.conv.weight"), value.unsqueeze(-1).unsqueeze(-1)
        legacy[key] = value
    assert any("inverted_conv" in k for k in legacy)
    missing, unexpected = model.load_state_dict(legacy, strict=True)
    assert not missing and not unexpected
    # raw-dict consumers use the shared helper
    n = m.migrate_glumbconv_state_dict(legacy)
    assert n > 0
    assert all("inverted_conv" not in k and "point_conv" not in k for k in legacy)
