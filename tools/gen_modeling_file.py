"""Regenerate modeling_boomer_fla.py from the training sources.

The HF-export modeling file used to be a hand-synced copy of
boomer/models/boomer_fla_dit.py and drifted every time the training model grew a
feature (shared-adaLN, fourier timesteps, the v6 joint-refresh/sandwich/NTK trio
were all missing at one point) — publishing checkpoints that silently ran the
wrong architecture. This script assembles the modeling file mechanically:

    header (docstring + imports)
  + the latent_dit classes the model imports (inlined verbatim)
  + boomer/models/boomer_fla_dit.py from after its import block to EOF (verbatim)
  + an HF loading tail (``from_pretrained`` + dtype/device properties)

Run after ANY change to boomer/models/boomer_fla_dit.py or the inlined
latent_dit classes:

    python tools/gen_modeling_file.py          # rewrite modeling_boomer_fla.py
    python tools/gen_modeling_file.py --check  # exit 1 if the file is stale

tests/test_modeling_sync.py runs the --check mode so CI catches drift.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

TRAIN_MODEL = REPO_ROOT / "boomer" / "models" / "boomer_fla_dit.py"
LATENT_DIT = REPO_ROOT / "boomer" / "models" / "latent_dit.py"
OUT_FILE = REPO_ROOT / "modeling_boomer_fla.py"

# Classes boomer_fla_dit.py imports from latent_dit — inlined in this order.
INLINED_CLASSES = (
    "AttentionRMSNorm",
    "CaptionEmbedder",
    "FourierTimestepEmbedder",
    "TimestepEmbedder",
)

HEADER = '''"""BoomerFLADiT model — self-contained for HuggingFace trust_remote_code distribution.

All dependencies inlined: no boomer package import needed.
External pip requirements: torch, flash-linear-attention (fla).

AUTO-GENERATED by tools/gen_modeling_file.py from boomer/models/boomer_fla_dit.py
and boomer/models/latent_dit.py — DO NOT EDIT BY HAND. Edit the sources, then:

    python tools/gen_modeling_file.py
"""
from __future__ import annotations

import math
import sys
import types
from dataclasses import dataclass
from pathlib import Path

import torch
from torch import nn
import torch.nn.functional as F
from torch.utils.checkpoint import checkpoint as _ckpt

# ── inlined from boomer/models/latent_dit.py ─────────────────────────────────
'''

TAIL = '''

# ── HF snapshot loading (modeling-file only; not part of the training model) ──
def _boomer_from_pretrained(cls, pretrained_model_name_or_path: str,
                            subfolder: str | None = None, **kwargs):
    """Load BoomerFLADiT weights from a local snapshot directory."""
    import json
    from pathlib import Path
    from safetensors.torch import load_file

    requested_dtype = kwargs.pop("torch_dtype", None) or kwargs.pop("dtype", None)
    path = Path(pretrained_model_name_or_path)
    if subfolder:
        path = path / subfolder

    cfg_raw = json.loads((path / "config.json").read_text())
    cfg_clean = {k: v for k, v in cfg_raw.items() if not k.startswith("_")}
    model_config = BoomerFLADiTConfig(**cfg_clean)

    model = cls(model_config)
    sd = load_file(str(path / "diffusion_pytorch_model.safetensors"))
    # Export verification already guarantees an exact denoise-path state dict. Keep
    # loading strict here too: silently accepting a stale config or truncated upload
    # produces plausible but invalid images and is much harder to diagnose than a clear
    # load-time error. RoPE tables are non-persistent buffers and therefore absent from
    # both sides of strict state-dict matching by design.
    model.load_state_dict(sd, strict=True)
    if requested_dtype is not None:
        model = model.to(dtype=requested_dtype)

    # Attach inference metadata so BoomerPipeline.__init__ can read without a separate file.
    model._boomer_cfg = {k: v for k, v in cfg_raw.items() if k.startswith("_")}
    # Store snapshot root so the pipeline can add it to sys.path for sibling imports.
    model._snapshot_dir = str(path.parent if subfolder else path)
    return model


BoomerFLADiT.from_pretrained = classmethod(_boomer_from_pretrained)
BoomerFLADiT.dtype = property(lambda self: next(self.parameters()).dtype)
BoomerFLADiT.device = property(lambda self: next(self.parameters()).device)
'''


def _extract_class(source: str, name: str) -> str:
    """One top-level class, from its `class` line to the next top-level statement."""
    lines = source.splitlines(keepends=True)
    out: list[str] = []
    capturing = False
    for line in lines:
        if line.startswith(f"class {name}"):
            capturing = True
        elif capturing and line.strip() and not line[0].isspace():
            break
        if capturing:
            out.append(line)
    if not out:
        raise SystemExit(f"class {name} not found in {LATENT_DIT}")
    return "".join(out).rstrip() + "\n"


def _train_model_body(source: str) -> str:
    """Everything after the boomer.models.latent_dit import block."""
    lines = source.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.startswith("from boomer.models.latent_dit import"):
            j = i
            if "(" in line and ")" not in line:
                while ")" not in lines[j]:
                    j += 1
            body = "".join(lines[j + 1 :])
            return body.lstrip("\n")
    raise SystemExit(f"latent_dit import block not found in {TRAIN_MODEL}")


def generate() -> str:
    latent_src = LATENT_DIT.read_text(encoding="utf-8")
    train_src = TRAIN_MODEL.read_text(encoding="utf-8")
    inlined = "\n\n".join(_extract_class(latent_src, name) for name in INLINED_CLASSES)
    return HEADER + inlined + "\n\n" + _train_model_body(train_src) + TAIL


def main() -> int:
    content = generate()
    if "--check" in sys.argv:
        current = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.exists() else ""
        if current != content:
            print(f"STALE: {OUT_FILE.name} does not match the training sources. "
                  "Rerun: python tools/gen_modeling_file.py")
            return 1
        print(f"OK: {OUT_FILE.name} is current.")
        return 0
    OUT_FILE.write_text(content, encoding="utf-8")
    print(f"wrote {OUT_FILE} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
